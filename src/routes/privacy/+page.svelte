    <p>Depending on the features you use, CampusMart handles:</p>
    <ul>
      <li><strong>Account information:</strong> your email address, display name, account identifier, and authentication information managed through the sign-in provider.</li>
      <li><strong>Profile and contact preferences:</strong> profile photo, campus affiliation, and any WhatsApp number or notification preferences you choose to provide.</li>
