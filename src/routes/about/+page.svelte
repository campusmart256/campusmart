    <h2>What is CampusMart?</h2>
    <p>CampusMart is an online marketplace designed for university students in Uganda to discover, buy, and sell items with one another. Whether you have a calculator you no longer need, a textbook for the next semester, or furniture to pass on, CampusMart helps you connect with interested students.</p>
    <h2>How it works</h2>
    <ol><li>Sellers create a listing with photos, an item description, and an asking price.</li><li>Buyers explore listings, compare items, and contact sellers through the platform.</li><li>Buyers and sellers agree on the details of a transaction themselves.</li></ol>
